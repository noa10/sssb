-- Quotation requests survive message retention but are removed with their enquiry.
CREATE TABLE IF NOT EXISTS quotation_requests (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  conversation_id CHAR(36) CHARACTER SET ascii NOT NULL,
  customer_id BIGINT UNSIGNED NULL,
  request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  company_id VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NULL,
  company_name VARCHAR(160) NOT NULL,
  product_key VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
  product_name VARCHAR(200) NOT NULL,
  quantity INT UNSIGNED NULL,
  required_by DATE NULL,
  delivery_location VARCHAR(200) NOT NULL DEFAULT '',
  procurement_route ENUM('unsure','government','direct','support') NOT NULL DEFAULT 'unsure',
  message VARCHAR(4000) NOT NULL DEFAULT '',
  enquiry_type VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
  country VARCHAR(120) NOT NULL DEFAULT '',
  city VARCHAR(120) NOT NULL DEFAULT '',
  postal_code VARCHAR(30) NOT NULL DEFAULT '',
  navigation_area VARCHAR(120) NOT NULL DEFAULT '',
  region VARCHAR(120) NOT NULL DEFAULT '',
  contact_name VARCHAR(120) NOT NULL,
  contact_email VARCHAR(254) NOT NULL,
  contact_phone VARCHAR(50) NOT NULL,
  contact_company VARCHAR(160) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_quotation_request (conversation_id, request_id),
  INDEX idx_quotation_conversation_created (conversation_id, created_at, id),
  CONSTRAINT fk_quotation_conversation FOREIGN KEY (conversation_id) REFERENCES conversations(id) ON DELETE CASCADE,
  CONSTRAINT fk_quotation_customer FOREIGN KEY (customer_id) REFERENCES customer_accounts(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
